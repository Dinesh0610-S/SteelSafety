"""
risk_engine/ppe_violations.py
==============================
SQLite-backed store for PPE violation events generated by the CCTV camera feed.

Events are now persisted to the `ppe_violation_log` table so they survive server
restarts. The old in-memory PPE_VIOLATION_EVENTS list has been removed.
"""

from __future__ import annotations
import json
from datetime import datetime
from typing import List, Dict, Any, Optional

from db.database import SessionLocal
from db.models import PPEViolationLog


def _row_to_dict(row: PPEViolationLog) -> Dict[str, Any]:
    """Convert a SQLAlchemy row to the API-compatible dict format."""
    try:
        items = json.loads(row.ppe_items_missing)
    except Exception:
        items = []
    return {
        "id":                  row.id,
        "plant_id":            row.plant_id,
        "zone_id":             row.zone_id,
        "zone_name":           row.zone_name,
        "timestamp":           row.timestamp.isoformat() if row.timestamp else datetime.now().isoformat(),
        "ppe_items_missing":   items,
        "confidence_pct":      row.confidence_pct,
        "detection_method":    row.detection_method,
        "status":              row.status,
        "risk_score_at_time":  row.risk_score_at_time,
        "camera_id":           getattr(row, "camera_id", None),
        "source":              getattr(row, "source", "video_file"),
        "in_restricted_zone":  getattr(row, "in_restricted_zone", True),
    }


def record_violation(
    zone_id: str,
    zone_name: str,
    plant_id: str,
    ppe_items_missing: List[str],
    confidence_pct: float,
    detection_method: str,
    risk_score_at_time: Optional[float] = None,
    camera_id: Optional[str] = None,
    source: Optional[str] = "video_file",
    in_restricted_zone: bool = True,
) -> Dict[str, Any]:
    """
    Create and persist a new PPE violation event to SQLite.
    """
    db = SessionLocal()
    try:
        row = PPEViolationLog(
            plant_id=plant_id,
            zone_id=zone_id,
            zone_name=zone_name,
            timestamp=datetime.now(),
            ppe_items_missing=json.dumps(ppe_items_missing),
            confidence_pct=confidence_pct,
            detection_method=detection_method,
            status="open",
            risk_score_at_time=risk_score_at_time,
            camera_id=camera_id,
            source=source,
            in_restricted_zone=in_restricted_zone,
        )
        db.add(row)
        db.commit()
        db.refresh(row)
        return _row_to_dict(row)
    finally:
        db.close()


def get_violations(
    plant_id: Optional[str] = None,
    status: Optional[str] = None,
    limit: int = 100,
) -> List[Dict[str, Any]]:
    """
    Return violation events, newest first, from SQLite.
    """
    db = SessionLocal()
    try:
        q = db.query(PPEViolationLog).order_by(PPEViolationLog.timestamp.desc())
        if plant_id:
            q = q.filter(PPEViolationLog.plant_id == plant_id)
        if status:
            q = q.filter(PPEViolationLog.status == status)
        rows = q.limit(limit).all()
        return [_row_to_dict(r) for r in rows]
    finally:
        db.close()


def update_status(event_id: int, new_status: str) -> Optional[Dict[str, Any]]:
    """
    Update the status of a violation event in SQLite.
    Returns the updated dict, or None if not found.
    """
    db = SessionLocal()
    try:
        row = db.query(PPEViolationLog).filter(PPEViolationLog.id == event_id).first()
        if not row:
            return None
        row.status = new_status
        db.commit()
        db.refresh(row)
        return _row_to_dict(row)
    finally:
        db.close()
